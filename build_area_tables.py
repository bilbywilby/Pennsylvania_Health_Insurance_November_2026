#!/usr/bin/env python3
"""build_area_tables.py - per-rating-area summaries from the data/public CSVs + crosswalk JSON.

Writes report/rating_area_summaries.md and data/public/py2027_area_rate_ranges.csv.
Deliberately reports min-max ranges, NOT unweighted means: no enrollment weights are
verified, so a simple average of carrier rate changes would imply precision we do not have.
"""
import csv
import json
from collections import defaultdict
from decimal import Decimal as D
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PUB = ROOT / "data" / "public"


def main():
    xw = json.loads((PUB / "pa_county_fips_crosswalk.json").read_text())
    rates = {}
    with open(PUB / "py2027_individual_rates_pid_2026-09-18.csv", newline="") as f:
        for r in csv.DictReader(f):
            rates[r["carrier_pid_name"]] = (D(r["requested_pct"]), D(r["approved_pct"]))
    fp = defaultdict(list)
    with open(PUB / "py2027_carrier_footprint_by_area.csv", newline="") as f:
        for r in csv.DictReader(f):
            fp[r["rating_area"]].append(r)

    out_rows, md = [], []
    md.append("# Rating-area summaries, PY2027 individual market\n")
    md.append("*Generated by `scripts/build_area_tables.py`. Approved rates: PID, 2026-09-18 (VERIFIED). "
              "Footprints: carried from the 2026-09-08 area reports (area-level: a carrier is listed if it covers at least one county in the area). "
              "Ranges are across carriers, unweighted; they are not the rate an enrollee in that area will see.*\n")
    for a in sorted(xw, key=int):
        counties = [c["county"] for c in xw[a]]
        ents = fp[a]
        known = [(e["entity_as_listed_in_area_report"], rates[e["pid_release_name"]])
                 for e in ents if e["pid_release_name"] in rates]
        missing = [e["entity_as_listed_in_area_report"] for e in ents if e["pid_release_name"] not in rates]
        lo = min(known, key=lambda t: t[1][1])
        hi = max(known, key=lambda t: t[1][1])
        out_rows.append([a, len(counties), len(ents), len(known), lo[1][1], lo[0], hi[1][1], hi[0], "; ".join(missing)])
        md.append(f"## Rating Area {a} ({len(counties)} counties)\n")
        md.append("**Counties:** " + ", ".join(counties) + "\n")
        md.append(f"**Carrier entities listed in area:** {len(ents)} ({len(known)} with a PID approved rate)\n")
        md.append("| Entity | Requested % | Approved % |")
        md.append("|---|---:|---:|")
        for name, (rq, ap) in sorted(known, key=lambda t: -t[1][1]):
            md.append(f"| {name} | {rq} | {ap} |")
        md.append("")
        md.append(f"**Approved range:** {lo[1][1]}% ({lo[0]}) to {hi[1][1]}% ({hi[0]}).")
        if missing:
            md.append(f"**No PID figure in the 2026-09-18 release for:** {'; '.join(missing)}.")
        md.append("")
    (ROOT / "report" / "rating_area_summaries.md").write_text("\n".join(md) + "\n")
    with open(PUB / "py2027_area_rate_ranges.csv", "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["rating_area", "n_counties", "n_entities_listed", "n_with_pid_rate",
                    "approved_min_pct", "approved_min_entity", "approved_max_pct", "approved_max_entity",
                    "entities_without_pid_rate"])
        w.writerows(out_rows)
    print("[OK] rating_area_summaries.md and py2027_area_rate_ranges.csv written")


if __name__ == "__main__":
    main()
